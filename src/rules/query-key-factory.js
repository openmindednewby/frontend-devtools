const QUERY_KEY = 'queryKey';
const TEST_FILE = /(?:\.(?:test|spec)\.[cm]?[jt]sx?$)|(?:\/__tests__\/)/;
const FACTORY_FILE = /[kK]eys?(?:Factory)?\.[cm]?[jt]sx?$/;
const DEFAULT_ALLOWED_PATH_FRAGMENTS = ['/generated/', '/autoGeneratedHooks/'];
const INLINE_KEY_TYPES = new Set(['ArrayExpression', 'Literal', 'TemplateLiteral']);
const TYPE_WRAPPERS = new Set(['TSAsExpression', 'TSSatisfiesExpression', 'TSNonNullExpression']);

function normalisePath(filename) {
  return typeof filename === 'string' ? filename.split('\\').join('/') : '';
}

function isExemptFile(filename, allow) {
  const path = normalisePath(filename);
  if (TEST_FILE.test(path)) return true;
  if (FACTORY_FILE.test(path)) return true;
  return [...DEFAULT_ALLOWED_PATH_FRAGMENTS, ...allow].some((fragment) => path.includes(fragment));
}

function unwrap(node) {
  let current = node;
  while (current && TYPE_WRAPPERS.has(current.type)) current = current.expression;
  return current;
}

function isQueryKeyProperty(node) {
  if (node.computed) return false;
  if (node.key.type === 'Identifier') return node.key.name === QUERY_KEY;
  return node.key.type === 'Literal' && node.key.value === QUERY_KEY;
}

const rule = {
  meta: {
    type: 'suggestion',
    docs: {
      description: 'PAT-QUERY-KEY-1: a React Query queryKey comes from a key factory, never an inline literal.',
    },
    schema: [
      {
        type: 'object',
        properties: { allow: { type: 'array', items: { type: 'string' } } },
        additionalProperties: false,
      },
    ],
    messages: {
      inlineKey:
        'Inline queryKey literal. Build it with a key factory (e.g. clientKeys.detail(id) from clientKeys.ts) so the query and its invalidation share one key.',
    },
  },
  create(context) {
    const options = context.options[0] ?? {};
    const allow = Array.isArray(options.allow) ? options.allow : [];
    const filename = context.filename ?? context.getFilename();
    if (isExemptFile(filename, allow)) return {};

    return {
      Property(node) {
        if (!isQueryKeyProperty(node)) return;
        const value = unwrap(node.value);
        if (value && INLINE_KEY_TYPES.has(value.type)) context.report({ node: node.value, messageId: 'inlineKey' });
      },
    };
  },
};

export default { rules: { 'query-key-factory': rule } };
